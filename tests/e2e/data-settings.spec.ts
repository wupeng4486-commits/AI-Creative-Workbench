import { expect, test } from "@playwright/test";
import fs from "node:fs";

test("设置页备份下载、恢复取消、坏包与完整恢复刷新 (BACK-01 至 BACK-04)", async ({ page, request }) => {
  const original = await (await request.post("/api/skills", { data: { name: "备份保留技能", scenario: "交付检查" } })).json();
  await page.goto("/settings");
  const before = await (await request.get("/api/system/info")).json();
  await expect(page.getByText(before.dataDir, { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "导出完整备份", exact: true }).click();
  await expect(page.getByText("完整备份已生成，可下载保存。")).toBeVisible();
  const downloadWait = page.waitForEvent("download");
  await page.getByRole("link", { name: "下载完整备份" }).first().click();
  const download = await downloadWait;
  const backupPath = (await download.path())!;
  const backupFile = { name: download.suggestedFilename(), mimeType: "application/zip", buffer: fs.readFileSync(backupPath) };
  await page.getByLabel("上传备份并校验").setInputFiles(backupFile);
  const preview = page.getByRole("dialog", { name: "确认完整恢复" });
  await expect(preview).toBeVisible();
  await preview.getByRole("button", { name: "取消恢复" }).click();
  await expect(preview).toBeHidden();
  expect((await (await request.get("/api/system/info")).json()).datasetId).toBe(before.datasetId);
  await page.getByLabel("上传备份并校验").setInputFiles({ name: "损坏.zip", mimeType: "application/zip", buffer: Buffer.from("invalid zip") });
  await expect(page.getByRole("alert")).toContainText(/格式错误|无法读取/);
  expect((await request.get(`/api/skills/${original.skill.id}`)).ok()).toBe(true);
  const later = await (await request.post("/api/skills", { data: { name: "备份之后新增", scenario: "交付检查" } })).json();
  await page.getByLabel("上传备份并校验").setInputFiles(backupFile);
  await expect(preview).toBeVisible();
  await preview.getByRole("button", { name: "确认替换当前数据集" }).click();
  await expect(page.getByText("完整恢复成功，已重新读取当前数据集。")).toBeVisible();
  expect((await (await request.get("/api/system/info")).json()).datasetId).not.toBe(before.datasetId);
  expect((await request.get(`/api/skills/${original.skill.id}`)).ok()).toBe(true);
  expect((await request.get(`/api/skills/${later.skill.id}`)).status()).toBe(404);
});

test("共用入口、显示偏好、清空二次确认与补充示例 (CFG-01、EMPTY-01)", async ({ page, request }) => {
  await page.goto("/settings");
  await page.getByLabel("LibTV 网页地址", { exact: true }).fill("https://example.com/t22");
  await page.getByRole("button", { name: "保存LibTV入口" }).click();
  await expect(page.getByText("LibTV入口已保存")).toBeVisible();
  await page.getByLabel("资产显示方式").selectOption("grid");
  await expect(page.getByLabel("资产显示方式")).toHaveValue("grid");
  await page.reload();
  await expect(page.getByLabel("资产显示方式")).toHaveValue("grid");
  await expect(page.getByLabel("LibTV 网页地址", { exact: true })).toHaveValue("https://example.com/t22");
  await request.post("/api/assets/import", { multipart: { file: { name: "偏好测试.txt", mimeType: "text/plain", buffer: Buffer.from("显示偏好") } } });
  await page.goto("/assets");
  await expect(page.getByTestId("asset-catalog")).toHaveAttribute("data-view", "grid");
  await page.goto("/settings");
  const backup = await (await request.post("/api/backups")).json();
  const zip = await (await request.get(backup.downloadUrl)).body();
  await page.getByRole("button", { name: "清空本机数据", exact: true }).click();
  const confirm = page.getByRole("dialog", { name: "二次确认清空数据" });
  await expect(confirm.getByRole("button", { name: "确认清空并切换" })).toBeDisabled();
  await confirm.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByRole("button", { name: "清空本机数据", exact: true }).click();
  await confirm.getByLabel("清空确认文字").fill("清空本机数据");
  await confirm.getByRole("button", { name: "确认清空并切换" }).click();
  await expect(page.getByText("已启用空数据集，可按需补充示例或恢复完整备份。")).toBeVisible();
  await page.goto("/home");
  await expect(page.getByText("暂无共享内容", { exact: true })).toBeVisible();
  const counts = (await (await request.get("/api/home")).json()).counts;
  expect(Object.values(counts)).toEqual([0, 0, 0, 0]);
  await page.goto("/settings");
  await page.getByRole("button", { name: "补充缺失示例" }).click();
  await expect(page.getByText("已补充缺失示例，已有资料与关联保留当前内容。")).toBeVisible();
  expect((await (await request.get("/api/home")).json()).counts.agents).toBe(6);
  await page.getByLabel("上传备份并校验").setInputFiles({ name: "恢复测试前资料.zip", mimeType: "application/zip", buffer: zip });
  await page.getByRole("dialog", { name: "确认完整恢复" }).getByRole("button", { name: "确认替换当前数据集" }).click();
  await expect(page.getByText("完整恢复成功，已重新读取当前数据集。")).toBeVisible();
});
