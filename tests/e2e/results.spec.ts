import fs from "node:fs";
import path from "node:path";
import { expect, test } from "@playwright/test";

test("同一成果只归档一次，来源冻结并可另存团队流程 (ST-05、WF-03)", async ({ page }) => {
  const imported = await page.request.post("/api/assets/import", { multipart: { file: { name: "T20参考图.png", mimeType: "image/png", buffer: fs.readFileSync(path.resolve(import.meta.dirname, "../../fixtures/demo/测试产品图.png")) } } });
  expect(imported.ok()).toBe(true);
  await page.goto("/studio/ai_image");
  const creation = page.waitForResponse((response) => response.url().endsWith("/api/drafts") && response.request().method() === "POST");
  await page.getByRole("button", { name: "新建草稿", exact: true }).click();
  const draft = (await (await creation).json()).draft;
  await expect(page).toHaveURL(new RegExp(`/studio/ai_image/${draft.id}$`));
  await page.getByLabel("创作要求", { exact: true }).fill("T20 原始制作需求");
  await page.getByLabel("选择工作流", { exact: true }).selectOption("seed-workflow-tietie");
  await page.getByLabel("选择商品", { exact: true }).selectOption("seed-product-sunscreen");
  await page.getByLabel("素材 T20参考图.png", { exact: true }).check();
  await page.getByLabel("风格要求", { exact: true }).fill("T20 柔光产品图");
  await page.getByLabel("候选数量", { exact: true }).fill("1");
  await page.getByRole("button", { name: "开始制作演示", exact: true }).click();
  const preview = page.getByRole("article", { name: "制作预览", exact: true });
  await expect(preview.getByRole("heading", { name: "制作演示完成", exact: true })).toBeVisible();
  const runId = await preview.getByLabel("制作历史", { exact: true }).inputValue();
  const before = (await (await page.request.get("/api/system/info")).json()).counts;
  await preview.getByRole("button", { name: "归档成果", exact: true }).click();
  const archive = page.getByRole("dialog", { name: "归档成果", exact: true });
  await archive.getByLabel("成果名称", { exact: true }).fill("T20 已归档主图");
  await archive.getByLabel("成果标签", { exact: true }).fill("T20, 主图");
  await archive.getByRole("button", { name: "确认归档", exact: true }).click();
  await expect(preview.getByText("已归档到资产库", { exact: false })).toBeVisible();
  const assetHref = (await preview.getByRole("link", { name: "查看归档资产", exact: true }).getAttribute("href"))!;
  await preview.getByRole("button", { name: "归档成果", exact: true }).click();
  await archive.getByRole("button", { name: "确认归档", exact: true }).click();
  await expect(preview.getByText("该成果已归档", { exact: false })).toBeVisible();
  expect((await (await page.request.get("/api/system/info")).json()).counts.assets).toBe(before.assets + 1);
  await page.getByLabel("创作要求", { exact: true }).fill("T20 后来修改的需求");
  await expect(page.getByText("已保存到本机", { exact: true })).toBeVisible();
  await page.goto(assetHref);
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("资产详情");
  const source = page.getByRole("article", { name: "制作来源", exact: true });
  await source.getByText("当时输入与参数", { exact: true }).click();
  await expect(source.locator("pre")).toContainText("T20 原始制作需求");
  await expect(source.locator("pre")).not.toContainText("T20 后来修改的需求");
  await source.getByRole("link", { name: "查看制作历史", exact: true }).click();
  await expect(preview.getByLabel("制作历史", { exact: true })).toHaveValue(runId);
  await preview.getByRole("button", { name: "另存为团队工作流", exact: true }).click();
  const workflow = page.getByRole("dialog", { name: "另存为团队工作流", exact: true });
  await workflow.getByLabel("另存工作流名称", { exact: true }).fill("T20 可复用图片流程");
  await workflow.getByRole("button", { name: "确认另存", exact: true }).click();
  await preview.getByRole("link", { name: "查看保存的工作流", exact: true }).click();
  await expect(page.getByLabel("LibTV 流程引用", { exact: true })).toHaveValue("libtv://workflow/tietie");
  await expect(page.getByLabel("默认参数", { exact: true })).toHaveValue(/T20 柔光产品图/);
  await expect(page.getByLabel("输入说明", { exact: true })).toHaveValue("T20 原始制作需求");
  expect((await (await page.request.get("/api/system/info")).json()).counts.workflows).toBe(before.workflows + 1);
});

test("外部成片手动导入保持真实来源与文件，重复导入不增加记录", async ({ page }) => {
  await page.goto("/studio/video_join");
  const creation = page.waitForResponse((response) => response.url().endsWith("/api/drafts") && response.request().method() === "POST");
  await page.getByRole("button", { name: "新建草稿", exact: true }).click();
  const draft = (await (await creation).json()).draft;
  await expect(page).toHaveURL(new RegExp(`/studio/video_join/${draft.id}$`));
  await page.getByLabel("简单输出要求", { exact: true }).fill("T20 外部剪辑成片来源");
  const before = (await (await page.request.get("/api/system/info")).json()).counts;
  await page.getByLabel("外部成片", { exact: true }).setInputFiles(path.resolve(import.meta.dirname, "../../fixtures/demo/测试视频B-6秒.mp4"));
  await page.getByLabel("外部成片名称", { exact: true }).fill("T20 手动导入成片");
  await page.getByRole("button", { name: "导入外部成片", exact: true }).click();
  const link = page.getByRole("link", { name: "查看外部成片", exact: true });
  await expect(link).toBeVisible();
  await page.getByRole("button", { name: "导入外部成片", exact: true }).click();
  await expect(link).toBeVisible();
  const after = (await (await page.request.get("/api/system/info")).json()).counts;
  expect(after.assets).toBe(before.assets + 1);
  expect(after.files).toBe(before.files + 1);
  await link.click();
  await expect(page.getByText("手动导入的交付成果", { exact: true })).toBeVisible();
  const video = page.locator("video");
  await expect.poll(() => video.evaluate((node) => node.readyState)).toBeGreaterThanOrEqual(2);
  expect(await video.evaluate((node) => node.duration)).toBe(6);
  await page.getByRole("article", { name: "制作来源", exact: true }).getByText("当时输入与参数", { exact: true }).click();
  await expect(page.locator("pre")).toContainText("T20 外部剪辑成片来源");
});
