import path from "node:path";
import { expect, test } from "@playwright/test";

test("三视频拖动与移动排序，移除后九秒且重开可播放 (JOIN-01、JOIN-02)", async ({ page }) => {
  await page.goto("/studio/video_join");
  const created = page.waitForResponse((response) => response.url().endsWith("/api/drafts") && response.request().method() === "POST");
  await page.getByRole("button", { name: "新建草稿", exact: true }).click();
  const draft = (await (await created).json()).draft;
  await expect(page).toHaveURL(new RegExp(`/studio/video_join/${draft.id}$`));
  await page.getByLabel("简单输出要求", { exact: true }).fill("T19 按 C、A 顺序输出");
  await page.getByLabel("添加本地视频", { exact: true }).setInputFiles(["测试视频A-4秒.mp4", "测试视频B-6秒.mp4", "测试视频C-5秒.mp4"].map((name) => path.resolve(import.meta.dirname, "../../fixtures/demo", name)));
  const list = page.getByRole("list", { name: "拼接片段", exact: true });
  await expect(list.getByRole("listitem")).toHaveCount(3);
  await expect(page.getByLabel("合计时长", { exact: true })).toHaveText("合计时长 15秒");
  // Begin the native drag before scrolling the destination into view.
  const sourceHandle = list.getByLabel("拖动片段 3", { exact: true });
  const targetHandle = list.getByLabel("拖动片段 1", { exact: true });
  await sourceHandle.scrollIntoViewIfNeeded();
  const sourceBox = (await sourceHandle.boundingBox())!;
  await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2);
  await page.mouse.down();
  await page.mouse.move(sourceBox.x + sourceBox.width / 2 + 12, sourceBox.y + sourceBox.height / 2, { steps: 5 });
  await targetHandle.scrollIntoViewIfNeeded();
  const targetBox = (await targetHandle.boundingBox())!;
  await page.mouse.move(targetBox.x + targetBox.width / 2, targetBox.y + targetBox.height / 2, { steps: 10 });
  await page.mouse.move(targetBox.x + targetBox.width / 2 + 1, targetBox.y + targetBox.height / 2 + 1);
  await page.mouse.up();
  const order = page.getByRole("list", { name: "片段顺序", exact: true }).getByRole("listitem");
  await expect(order).toHaveText(["测试视频C-5秒.mp4", "测试视频A-4秒.mp4", "测试视频B-6秒.mp4"]);
  await page.getByRole("button", { name: "下移片段 1", exact: true }).click();
  await expect(order).toHaveText(["测试视频A-4秒.mp4", "测试视频C-5秒.mp4", "测试视频B-6秒.mp4"]);
  await page.getByRole("button", { name: "上移片段 2", exact: true }).click();
  await page.getByRole("button", { name: "移除片段 3", exact: true }).click();
  await expect(order).toHaveText(["测试视频C-5秒.mp4", "测试视频A-4秒.mp4"]);
  await expect(page.getByLabel("合计时长", { exact: true })).toHaveText("合计时长 9秒");
  await page.getByRole("button", { name: "预览片段 1", exact: true }).click();
  const video = page.getByLabel("单片段预览", { exact: true });
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(2);
  expect(await video.evaluate((node: HTMLVideoElement) => node.duration)).toBe(5);
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("已保存到本机");
  await page.reload();
  await expect(order).toHaveText(["测试视频C-5秒.mp4", "测试视频A-4秒.mp4"]);
  await expect(page.getByLabel("合计时长", { exact: true })).toHaveText("合计时长 9秒");
  await page.getByRole("button", { name: "开始制作演示", exact: true }).click();
  const preview = page.getByRole("article", { name: "制作预览", exact: true });
  await expect(preview.getByRole("heading", { name: "制作演示完成", exact: true })).toBeVisible();
  await expect(preview.getByRole("region", { name: "拼接方案", exact: true })).toContainText("方案合计 9秒");
  await expect.poll(() => preview.locator("video").evaluate((node) => node.readyState)).toBeGreaterThanOrEqual(2);
});

test("剪映未配置时提示，配置后保存最新草稿再打开入口 (LINK-01)", async ({ page, context, baseURL }) => {
  await page.goto("/studio/video_join");
  const created = page.waitForResponse((response) => response.url().endsWith("/api/drafts") && response.request().method() === "POST");
  await page.getByRole("button", { name: "新建草稿", exact: true }).click();
  const draft = (await (await created).json()).draft;
  await expect(page).toHaveURL(new RegExp(`/studio/video_join/${draft.id}$`));
  const pagesBefore = context.pages().length;
  await page.getByRole("button", { name: "前往剪映", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "配置剪映入口", exact: true });
  await expect(dialog).toBeVisible();
  expect(context.pages()).toHaveLength(pagesBefore);
  const url = `${baseURL}/api/system/health?jianying=1`;
  await dialog.getByLabel("剪映网页地址", { exact: true }).fill(url);
  await dialog.getByRole("button", { name: "保存入口", exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.getByLabel("简单输出要求", { exact: true }).fill("打开剪映前的最新输出要求");
  const popupPromise = page.waitForEvent("popup");
  await page.getByRole("button", { name: "前往剪映", exact: true }).click();
  const popup = await popupPromise;
  await expect(popup).toHaveURL(url);
  const saved = await (await page.request.get(`/api/drafts/${draft.id}`)).json();
  expect(saved.draft.requirements).toBe("打开剪映前的最新输出要求");
  await expect(page.getByLabel("简单输出要求", { exact: true })).toHaveValue("打开剪映前的最新输出要求");
  await popup.close();
});
